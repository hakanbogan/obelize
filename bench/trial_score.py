"""Score the trial measurement, offline, from what was committed.

What `obelize upgrade --apply --yes` did over the repositories of the dry-run frames whose plan
writes a file (bench/trial_collect.py), as the docs/BENCHMARK_RESULTS.md block. With no record
committed there is no section: this module publishes nothing it was not given.
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
from collections import Counter
from pathlib import Path
from typing import Any

from . import read_yaml, trial_box
from .gate1_score import share

ROOT = Path(__file__).resolve().parent.parent
RECORDS = ROOT / "bench" / "results" / "trial"
DOCUMENT = ROOT / "docs" / "BENCHMARK_RESULTS.md"

MARKERS = (
    "<!-- trial:begin -- generated by bench/trial_score.py; edit that, not this -->",
    "<!-- trial:end -->",
)
HEADING = "## Upgrade trial"
INTRO = (
    "What `obelize upgrade --apply --yes` did in an isolated box over the repositories of the "
    "upgrade frames whose dry run writes a file; how it is measured is in "
    "[BENCHMARK.md](BENCHMARK.md#how-the-trial-is-measured)."
)
ROW = (
    "| [Upgrade trial](#upgrade-trial) | `bench/trial_score.py` "
    "| `tests/unit/test_bench_trial_score.py` |\n"
)
AFTER = "## Round 1"

MEANING = {
    ("fail", "tests_broke"): "a test that passed before the move broke",
    ("inconclusive", "no_tests"): "the repository has no tests the trial could run",
    ("inconclusive", "no_junit"): "the tests produced no result the trial can read",
    ("inconclusive", "timeout"): "the tests did not finish in time",
    ("inconclusive", "nothing_to_compare"): "no test passed before, or the move changed no file",
    ("inconclusive", "unresolved"): "a place was left for an agent that was not asked",
    ("error", "environment"): "the dependencies could not be installed",
    ("error", "copy"): "the repository is larger than a trial copies",
    ("error", "not_started"): "the trial refused to start",
    ("error", "write_failed"): "the trial passed and the write failed",
    ("error", "verdict_mismatch"): "the trial's line and its trial.json disagree",
    ("error", "exit_mismatch"): "the exit code does not fit the verdict",
    ("error", "oom"): "the container ran out of memory before a verdict",
    ("error", "disk"): "the container wrote past its disk limit",
    ("error", "container"): "the container could not be run",
    ("error", "fetch"): "the repository could not be fetched",
    ("error", "no_verdict"): "no verdict, and no cause the harness knows",
    ("timeout", "wall_clock"): "the container ran past its time limit",
}


# What a status with no trial says, so the table has the row.
NONE = {
    "fail": "a test that passed before the move broke",
    "inconclusive": "the tests could not judge the move",
    "error": "the trial did not reach a verdict",
    "timeout": "the container ran past its time limit",
}


def load() -> list[tuple[dict[str, Any], dict[str, Any]]]:
    """Each committed record with the frame it was drawn from; a malformed one stops the run."""
    loaded = []
    for path in sorted(RECORDS.glob("*.json")):
        record = json.loads(path.read_text(encoding="utf-8"))
        if problems := trial_box.validate_record(record):
            raise SystemExit(f"{path.name} is not a record: {'; '.join(problems)}")
        loaded.append((record, read_yaml(ROOT / record["frame"])))
    return loaded


def _rows(status: str, reasons: Counter[tuple[str, str | None]]) -> list[tuple[str | None, int]]:
    """The table rows of one status: one per reason it has, or a single row of none."""
    found = [(reason, count) for (kind, reason), count in reasons.items() if kind == status]
    return sorted(found, key=lambda one: (-one[1], str(one[0]))) or [(None, 0)]


def _outcomes(rows: list[dict[str, Any]]) -> list[str]:
    reasons = Counter((row["status"], row["reason"]) for row in rows)
    passed = [row for row in rows if row["status"] == "pass"]
    whole = sum(not row["partial"] for row in passed)
    lines = [
        "| Outcome | Repositories | Share of tried |",
        "|---|---:|---:|",
        f"| `pass`: the tests that passed before pass, the whole move written | {whole} "
        f"| {share(whole, len(rows))} |",
        f"| `pass`: the tests pass, and places were left for a person (`partial`) "
        f"| {len(passed) - whole} | {share(len(passed) - whole, len(rows))} |",
    ]
    for status in ("fail", "inconclusive", "error", "timeout"):
        for reason, count in _rows(status, reasons):
            name = (
                f"`{status}`: {NONE[status]}"
                if reason is None
                else f"`{status}`, `{reason}`: {MEANING[(status, reason)]}"
            )
            lines.append(f"| {name} | {count} | {share(count, len(rows))} |")
    return lines


def _sums(rows: list[dict[str, Any]]) -> str:
    passed = [row for row in rows if row["status"] == "pass"]
    compared = [row for row in rows if row["compared"]]
    seconds = sorted(row["seconds"] for row in rows)
    return (
        f"{sum(row['compared'] for row in rows)} tests that passed before were compared in "
        f"{len(compared)} trials; {sum(row['broken_count'] for row in rows)} broke and "
        f"{sum(row['flaky'] for row in rows)} failed once and passed again. The {len(passed)} "
        f"passing trials wrote {sum(row['written'] for row in passed)} files and left "
        f"{sum(row['held'] for row in passed)} files and {sum(row['places'] for row in passed)} "
        f"places for a person. A repository took {statistics.median(seconds):g} s at the median "
        f"and {seconds[-1]:g} s at the longest, {sum(seconds):g} s in all."
    )


def _section(
    title: str, rows: list[dict[str, Any]], provenance: list[str] | None = None
) -> list[str]:
    return [
        f"### {title}",
        "",
        *([*provenance, ""] if provenance else []),
        f"{len(rows)} repositories were tried.",
        "",
        *_outcomes(rows),
        "",
        _sums(rows),
    ]


def _provenance(record: dict[str, Any]) -> list[str]:
    limits, proxy, tested = record["limits"], record["proxy"] or {}, record["selftest"]
    carried = " and ".join(
        f"{count:,} connections to {host}" for host, count in sorted(proxy.get("allow", {}).items())
    )
    denied = sum(proxy.get("deny", {}).values())
    commit = record["obelize_commit"]
    built = f"from commit `{commit[:10]}`" if commit else "from a wheel built elsewhere"
    return [
        f"obelize {record['obelize_version']} {built} "
        f"(wheel sha256 `{record['wheel_sha256'][:12]}`), image `{record['image'][7:19]}`, "
        f"Docker {record['docker']}, {record['uv']}, Linux {record['machine']}, run on "
        f"{record['date']}. Each container had {limits['memory_gb']} GiB of memory, "
        f"{limits['cpus']} CPUs, {limits['pids']:,} processes, {limits['disk_gb']} GiB of disk and "
        f"{limits['wall_s'] // 60} minutes. The self-test passed at {tested['at']} after "
        f"{sum(tested['attempts'].values())} attempts to get out or to be refused. The proxy "
        f"carried {carried or 'nothing'} and refused {denied}."
    ]


def biases(records: list[tuple[dict[str, Any], dict[str, Any]]]) -> str:
    """The reasons these numbers are not a rate over repositories, from what the records hold."""
    tried = sum(len(record["trial"]) for record, _ in records)
    drawn = sum(len(frame["repositories"]) for _, frame in records)
    rows = [row for record, _ in records for row in record["trial"]]
    partial = sum(bool(row["partial"]) for row in rows)
    machines = sorted({str(record["machine"]) for record, _ in records})
    pythons = sorted(
        {minor for record, _ in records for minor in record["pythons"]},
        key=lambda minor: tuple(int(part) for part in minor.split(".")),
    )
    unit = sorted({str(record["dry_run"]["unit"] or "repository") for record, _ in records})
    return (
        f"These {tried} repositories are the ones of the {drawn} drawn whose dry run writes a file "
        f"(a plan written by the {' and '.join(unit)} rule), so a repository the plan could not "
        "write is not here. The frames were drawn by code search of public repositories that "
        "import the old API, which favours small single-purpose projects. The trial installs "
        "what the repository's own recipe names and runs pytest, since no test command is known; "
        "a repository with another way of testing is `inconclusive`. A `pass` means the tests "
        "that existed and passed before still pass: it says nothing about code no test reaches, "
        f"and {partial} of the passes left places for a person. The box is a Linux container "
        f"({', '.join(machines)}) with a fixed uv, Pythons {', '.join(pythons)} (one chosen per "
        "repository by its `requires-python`) and the packages the index held on the day, so a "
        "repository that needs a service, a secret, a system library the image lacks or more "
        "memory, time or disk than the limits above ends as `error`, `inconclusive` or "
        "`timeout`, and the passes lean towards self-contained suites."
    )


def render(records: list[tuple[dict[str, Any], dict[str, Any]]]) -> str:
    """The generated block; none where there is no record."""
    if not records:
        return ""
    lines: list[str] = []
    for record, _ in records:
        title = f"`{record['distribution']}` {record['from']} to {record['to']}"
        lines += [*_section(title, record["trial"], _provenance(record)), ""]
    if len(records) > 1:
        every = [row for record, _ in records for row in record["trial"]]
        lines += [*_section("All frames", every), ""]
    lines += ["### What these numbers are not", "", biases(records)]
    return "\n".join(lines)


def block(text: str) -> str | None:
    """The generated block of the document, or none where it has no section for it."""
    begin, end = MARKERS
    if begin not in text or end not in text:
        return None
    return text.split(begin, 1)[1].split(end, 1)[0].strip("\n")


def written(text: str, generated: str) -> str:
    """The document with its block replaced, or with a section for the block put before Round 1."""
    begin, end = MARKERS
    if block(text) is not None:
        head, rest = text.split(begin, 1)
        return f"{head}{begin}\n\n{generated}\n\n{end}{rest.split(end, 1)[1]}"
    section = f"{HEADING}\n\n{INTRO}\n\n{begin}\n\n{generated}\n\n{end}\n\n"
    rowed = text.replace("\n| [Round 1]", f"\n{ROW}| [Round 1]", 1)
    return rowed.replace(f"\n{AFTER}\n", f"\n{section}{AFTER}\n", 1)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Score the trial measurement.")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail when the document is stale")
    mode.add_argument("--write", action="store_true", help="put the block into the document")
    arguments = parser.parse_args(argv)
    generated = render(load())
    if not (arguments.check or arguments.write):
        print(generated)
        return 0
    text = DOCUMENT.read_text(encoding="utf-8")
    if arguments.write:
        if not generated:
            raise SystemExit("no record of the trial measurement to write")
        DOCUMENT.write_text(written(text, generated), encoding="utf-8")
        return 0
    if block(text) == (generated or None):
        print(f"{DOCUMENT.name} is up to date with bench/results/trial/")
        return 0
    print(f"{DOCUMENT.name} is stale; run `python -m bench.trial_score --write`")
    return 1


if __name__ == "__main__":  # pragma: no cover - the module is imported by its test
    sys.exit(main())
