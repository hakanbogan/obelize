"""Score the `fix` dry-run measurement, offline, from what was committed.

What the rules alone would write over a stratified frame of repositories that use a pack's
library (bench/gate1_collect.py `dryrun`), as the docs/BENCHMARK_RESULTS.md block.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path
from typing import Any

import yaml
from gate1_score import share

from obelize.models import ATOMICITY_BAIL, REPO_ATOMICITY_BAIL

ROOT = Path(__file__).resolve().parent.parent
RECORDS = ROOT / "bench" / "results" / "dryrun"
DOCUMENT = ROOT / "docs" / "BENCHMARK_RESULTS.md"

MARKERS = (
    "<!-- dryrun:begin -- generated by bench/dryrun_score.py; edit that, not this -->",
    "<!-- dryrun:end -->",
)

# Bails that name no cause of their own: another row held this one back.
DERIVED_BAILS: frozenset[str] = frozenset({ATOMICITY_BAIL, REPO_ATOMICITY_BAIL})

# Symbols shown per pack: the primary causes that hold back the most rows.
TOP_CAUSES = 10

# In the order a reader asks: does the pack run, does it find a usage, does it write, all of it.
TIERS: tuple[tuple[str, str], ...] = (
    ("blocked", "the pack stops before it plans, for the reason below"),
    ("none", "no usage found"),
    ("held", "usages found, no file written"),
    ("partial", "a file written, a row withheld"),
    ("complete", "a file written, nothing withheld"),
)


def tier(record: dict[str, Any]) -> str:
    if record["blocked"]:
        return "blocked"
    if not record["used"]:
        return "none"
    if not record["files"]:
        return "held"
    return "partial" if record["withheld"] else "complete"


def withheld(records: list[dict[str, Any]]) -> list[tuple[str, int, int]]:
    """`(bail, rows, repositories)` for every withheld row, most rows first."""
    rows: Counter[str] = Counter()
    repositories: Counter[str] = Counter()
    for record in records:
        held = [row["bail"] for row in record["withheld"]]
        rows.update(held)
        repositories.update(set(held))
    return sorted(
        ((bail, count, repositories[bail]) for bail, count in rows.items()),
        key=lambda row: (-row[1], row[0]),
    )


def causes(records: list[dict[str, Any]]) -> list[tuple[str, str, int, int]]:
    """`(symbol, bail, rows, repositories)` for the rows with a cause of their own."""
    rows: Counter[tuple[str, str]] = Counter()
    repositories: Counter[tuple[str, str]] = Counter()
    for record in records:
        held = [
            (row["symbol"] or "(none)", row["bail"])
            for row in record["withheld"]
            if row["bail"] not in DERIVED_BAILS
        ]
        rows.update(held)
        repositories.update(set(held))
    return sorted(
        (
            (symbol, bail, count, repositories[symbol, bail])
            for (symbol, bail), count in rows.items()
        ),
        key=lambda row: (-row[2], row[0], row[1]),
    )


def load() -> list[tuple[dict[str, Any], dict[str, Any]]]:
    """Each committed record with the frame it was drawn from."""
    loaded = []
    for path in sorted(RECORDS.glob("*.json")):
        record = json.loads(path.read_text(encoding="utf-8"))
        frame = yaml.safe_load((ROOT / record["frame"]).read_text(encoding="utf-8"))
        loaded.append((record, frame))
    return loaded


def _section(record: dict[str, Any], frame: dict[str, Any]) -> list[str]:
    scored = [row for row in record["dry_run"] if "error" not in row]
    counted = Counter(tier(row) for row in scored)
    ran = len(scored) - counted["blocked"]
    lines = [
        f"### `{record['pack']}`",
        "",
        f"obelize {record['obelize_version']}, pack sha256 `{record['pack_sha256'][:12]}`, "
        f"frame drawn {frame['queried_at']} for `{frame['term']}` "
        f"({frame['population']:,} files in the index): {len(scored)} repositories planned, "
        f"{len(record['dry_run']) - len(scored)} errored.",
        "",
        "| Outcome | Repositories | Share of planned | Share of those the pack ran on |",
        "|---|---:|---:|---:|",
    ]
    for name, meaning in TIERS:
        ran_on = "--" if name == "blocked" else share(counted[name], ran)
        lines.append(
            f"| `{name}`: {meaning} | {counted[name]} | {share(counted[name], len(scored))} "
            f"| {ran_on} |"
        )
    blocked = Counter((row["blocked"], bool(row["manifests"])) for row in scored if row["blocked"])
    if blocked:
        lines += [
            "",
            "| Why the pack stopped | A manifest declares it | Repositories |",
            "|---|---|---:|",
        ]
        lines += [
            f"| `{code}` | {'yes' if declared else 'no'} | {count} |"
            for (code, declared), count in sorted(
                blocked.items(), key=lambda row: (-row[1], row[0])
            )
        ]
    held = withheld(scored)
    if held:
        lines += ["", "| Why a row was withheld | Rows | Repositories | |", "|---|---:|---:|---|"]
        for bail, rows, repositories in held:
            mark = "a consequence of another hold" if bail in DERIVED_BAILS else ""
            lines.append(f"| `{bail}` | {rows} | {repositories} | {mark} |")
        lines += [
            "",
            f"| The {TOP_CAUSES} symbols that hold back most rows | Bail | Rows | Repositories |",
            "|---|---|---:|---:|",
        ]
        lines += [
            f"| `{symbol}` | `{bail}` | {rows} | {repositories} |"
            for symbol, bail, rows, repositories in causes(scored)[:TOP_CAUSES]
        ]
    return lines


def render(records: list[tuple[dict[str, Any], dict[str, Any]]]) -> str:
    lines: list[str] = []
    for record, frame in records:
        lines += [*_section(record, frame), ""]
    return "\n".join(lines).rstrip("\n")


def block(text: str) -> str:
    begin, end = MARKERS
    if begin not in text or end not in text:
        raise SystemExit(f"{DOCUMENT.name} has no dryrun block; add both markers first")
    return text.split(begin, 1)[1].split(end, 1)[0].strip("\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Score the fix dry-run measurement.")
    parser.add_argument("--check", action="store_true", help="fail when the document is stale")
    arguments = parser.parse_args(argv)
    generated = render(load())
    if not arguments.check:
        print(generated)
        return 0
    if block(DOCUMENT.read_text(encoding="utf-8")) == generated:
        print(f"{DOCUMENT.name} is up to date with bench/results/dryrun/")
        return 0
    print(f"{DOCUMENT.name} is stale; run `python bench/dryrun_score.py` and paste the block")
    return 1


if __name__ == "__main__":  # pragma: no cover - the module is imported by its test
    sys.exit(main())
