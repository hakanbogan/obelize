"""Score the `upgrade` dry-run measurement, offline, from what was committed.

What a pack made from two releases would write, and what it only flags, over a frame of
repositories that still use the old API (bench/upgrade_collect.py), as the
docs/BENCHMARK_RESULTS.md block. The tiers and the reasons are `dryrun_score`'s.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path
from typing import Any

from . import read_yaml
from .dryrun_score import DERIVED_BAILS, TIERS, TOP_CAUSES, causes, tier, withheld
from .gate1_score import share

ROOT = Path(__file__).resolve().parent.parent
RECORDS = ROOT / "bench" / "results" / "upgrade"
DOCUMENT = ROOT / "docs" / "BENCHMARK_RESULTS.md"

MARKERS = (
    "<!-- upgrade:begin -- generated by bench/upgrade_score.py; edit that, not this -->",
    "<!-- upgrade:end -->",
)

# What a usage that no rule rewrites and the pack does not just flag is called in the table.
OTHER = "held for a cause of its own"


def usages(records: list[dict[str, Any]]) -> list[tuple[str, int, int]]:
    """`(what became of it, usages, repositories)` for every usage found; the rows sum to all."""
    counts: Counter[str] = Counter()
    repositories: Counter[str] = Counter()
    for row in records:
        own = {
            **{f"a rule rewrites it (`{kind}`)": count for kind, count in row["rules"].items()},
            "the pack flags it and never rewrites it": row["flagged"],
            OTHER: row["used"] - sum(row["rules"].values()) - row["flagged"],
        }
        counts.update(own)
        repositories.update(name for name, count in own.items() if count)
    return sorted(
        ((name, count, repositories[name]) for name, count in counts.items() if count),
        key=lambda row: (-row[1], row[0]),
    )


def load() -> list[tuple[dict[str, Any], dict[str, Any]]]:
    """Each committed record with the frame it was drawn from."""
    loaded = []
    for path in sorted(RECORDS.glob("*.json")):
        record = json.loads(path.read_text(encoding="utf-8"))
        loaded.append((record, read_yaml(ROOT / record["frame"])))
    return loaded


def _section(record: dict[str, Any], frame: dict[str, Any]) -> list[str]:
    scored = [row for row in record["upgrade"] if "error" not in row]
    counted = Counter(tier(row) for row in scored)
    ran = len(scored) - counted["blocked"]
    using = [row for row in scored if row["used"]]
    lines = [
        f"### `{record['distribution']}` {record['from']} to {record['to']}",
        "",
        f"obelize {record['obelize_version']}, pack `{record['pack']}` sha256 "
        f"`{record['pack_sha256'][:12]}` (made from the two releases in "
        f"{record['synth_seconds']:g} s), frame drawn {frame['queried_at']} for `{frame['term']}` "
        f"({frame['population']:,} files in the index): {len(scored)} repositories planned, "
        f"{len(record['upgrade']) - len(scored)} errored, {len(using)} with a usage.",
        "",
        "| Outcome | Repositories | Share of planned | Share of those the pack ran on |",
        "|---|---:|---:|---:|",
    ]
    for name, meaning in TIERS:
        ran_on = "--" if name == "blocked" else share(counted[name], ran)
        lines.append(
            f"| `{name}`: {meaning} | {counted[name]} | {share(counted[name], len(scored))} "
            f"| {ran_on} |"
        )
    # The exception and, for a failed command, its exit code: the rest names a path or a clone.
    errors = Counter(
        re.sub(r"^(\w+(?:: exit \d+)?).*", r"\1", row["error"], flags=re.DOTALL)
        for row in record["upgrade"]
        if "error" in row
    )
    if errors:
        lines += ["", "| Why a repository errored | Repositories |", "|---|---:|"]
        lines += [f"| `{error}` | {count} |" for error, count in errors.most_common()]
    total = sum(row["used"] for row in scored)
    lines += [
        "",
        f"| What became of a usage | Usages | Share of {total} | Repositories |",
        "|---|---:|---:|---:|",
    ]
    lines += [
        f"| {name} | {count} | {share(count, total)} | {repositories} |"
        for name, count, repositories in usages(scored)
    ]
    kept = sum(row["written"] for row in scored if row["files"])
    lines += [
        "",
        f"{kept} of the {total} usages are in a file the dry run would write: it writes a "
        f"repository's plan only when nothing in it is left (`complete` above).",
    ]
    blocked = Counter((row["blocked"], bool(row["manifests"])) for row in scored if row["blocked"])
    if blocked:
        lines += [
            "",
            "| Why the pack stopped | A manifest declares it | Repositories |",
            "|---|---|---:|",
        ]
        lines += [
            f"| `{code}` | {'yes' if declared else 'no'} | {count} |"
            for (code, declared), count in sorted(
                blocked.items(), key=lambda row: (-row[1], row[0])
            )
        ]
    held = withheld(scored)
    if held:
        lines += ["", "| Why a row was withheld | Rows | Repositories | |", "|---|---:|---:|---|"]
        for bail, rows, repositories in held:
            mark = "a consequence of another hold" if bail in DERIVED_BAILS else ""
            lines.append(f"| `{bail}` | {rows} | {repositories} | {mark} |")
        lines += [
            "",
            f"| The {TOP_CAUSES} symbols that hold back most rows | Bail | Rows | Repositories |",
            "|---|---|---:|---:|",
        ]
        lines += [
            f"| `{symbol}` | `{bail}` | {rows} | {repositories} |"
            for symbol, bail, rows, repositories in causes(scored)[:TOP_CAUSES]
        ]
    return lines


def render(records: list[tuple[dict[str, Any], dict[str, Any]]]) -> str:
    lines: list[str] = []
    for record, frame in records:
        lines += [*_section(record, frame), ""]
    return "\n".join(lines).rstrip("\n")


def block(text: str) -> str:
    begin, end = MARKERS
    if begin not in text or end not in text:
        raise SystemExit(f"{DOCUMENT.name} has no upgrade block; add both markers first")
    return text.split(begin, 1)[1].split(end, 1)[0].strip("\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Score the upgrade dry-run measurement.")
    parser.add_argument("--check", action="store_true", help="fail when the document is stale")
    arguments = parser.parse_args(argv)
    generated = render(load())
    if not arguments.check:
        print(generated)
        return 0
    if block(DOCUMENT.read_text(encoding="utf-8")) == generated:
        print(f"{DOCUMENT.name} is up to date with bench/results/upgrade/")
        return 0
    print(f"{DOCUMENT.name} is stale; run `python -m bench.upgrade_score` and paste the block")
    return 1


if __name__ == "__main__":  # pragma: no cover - the module is imported by its test
    sys.exit(main())
